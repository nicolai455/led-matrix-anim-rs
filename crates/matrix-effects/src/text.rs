pub fn get_glyph(c: char) -> &'static [u8; 5] {
    let code = c as u32;
    if (32..=126).contains(&code) {
        &FONT_DATA[(code - 32) as usize]
    } else {
        &FONT_DATA[0] // space
    }
}

pub fn text_width(text: &str) -> usize {
    let mut width = 0;
    for _ in text.chars() {
        width += FONT_WIDTH + FONT_SPACING;
    }
    if width > 0 {
        width - FONT_SPACING
    } else {
        0
    }
}

pub fn draw_char(frame: &mut Frame, c: char, x: i32, y: i32, color: Rgb) -> usize {
    let glyph = get_glyph(c);
    for row in 0..FONT_HEIGHT {
        for (col, &col_bits) in glyph.iter().enumerate().take(FONT_WIDTH) {
            let px = x + col as i32;
            let py = y + row as i32;
            if px >= 0
                && px < WIDTH as i32
                && py >= 0
                && py < HEIGHT as i32
                && (col_bits & (1 << row)) != 0
            {
                frame.set(px as usize, py as usize, color);
            }
        }
    }
    FONT_WIDTH + FONT_SPACING
}

pub fn draw_text(frame: &mut Frame, text: &str, mut x: i32, y: i32, color: Rgb) -> usize {
    let start_x = x;
    for c in text.chars() {
        x += draw_char(frame, c, x, y, color) as i32;
    }
    (x - start_x).max(0) as usize
}

pub fn draw_centered_text(frame: &mut Frame, text: &str, y: i32, color: Rgb) {
    let w = text_width(text);
    let x = (WIDTH as i32 - w as i32) / 2;
    draw_text(frame, text, x, y, color);
}

pub struct TextStaticEffect {
    pub y: i32,
    pub centered: bool,
}

impl Default for TextStaticEffect {
    fn default() -> Self {
        Self {
            y: 12,
            centered: true,
        }
    }
}

impl TextStaticEffect {
    pub fn new() -> Self {
        Self::default()
    }
}

impl Effect for TextStaticEffect {
    fn id(&self) -> &'static str {
        "TextStatic"
    }

    fn name(&self) -> &'static str {
        "TextStatic"
    }

    fn reset(&mut self) {}

    fn render(&mut self, frame: &mut Frame, context: &RenderContext<'_>) {
        frame.clear(Rgb::BLACK);
        let color = if context.color == Rgb::BLACK {
            Rgb::WHITE
        } else {
            context.color
        };
        if self.centered {
            draw_centered_text(frame, context.text, self.y, color);
        } else {
            draw_text(frame, context.text, 0, self.y, color);
        }
    }
}

pub struct TextScrollEffect {
    pub y: i32,
    offset_x: f32,
    started: bool,
}

impl Default for TextScrollEffect {
    fn default() -> Self {
        Self {
            y: 12,
            offset_x: WIDTH as f32,
            started: false,
        }
    }
}

impl TextScrollEffect {
    pub fn new() -> Self {
        Self::default()
    }
}

impl Effect for TextScrollEffect {
    fn id(&self) -> &'static str {
        "TextScroll"
    }

    fn name(&self) -> &'static str {
        "TextScroll"
    }

    fn reset(&mut self) {
        self.offset_x = WIDTH as f32;
        self.started = false;
    }

    fn render(&mut self, frame: &mut Frame, context: &RenderContext<'_>) {
        frame.clear(Rgb::BLACK);
        let color = if context.color == Rgb::BLACK {
            Rgb::WHITE
        } else {
            context.color
        };
        let speed = if context.scroll_speed > 0.0 {
            context.scroll_speed
        } else {
            30.0
        };

        let dt = context.delta_seconds.clamp(0.0, 1.0);
        if !self.started {
            self.offset_x = WIDTH as f32;
            self.started = true;
        } else {
            self.offset_x -= speed * dt;
        }

        let total_w = text_width(context.text) as f32;
        if self.offset_x < -total_w {
            self.offset_x = WIDTH as f32;
        }

        draw_text(
            frame,
            context.text,
            self.offset_x.round() as i32,
            self.y,
            color,
        );
    }
}
